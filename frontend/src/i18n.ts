export type Lang = 'zh' | 'en'

export function t(
  key: keyof typeof messages.zh,
  lang: Lang,
  params?: number | string,
): string {
  const text =
    (messages[lang] as Record<string, string>)[key] ?? messages.zh[key] ?? key
  if (params == null) return text
  return text.replace(/\{n\}/g, String(params))
}
